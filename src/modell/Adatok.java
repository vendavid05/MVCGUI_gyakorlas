package modell;

public class Adatok {
    private String szoveg;
    private int szam;

    public Adatok(String szoveg, int szam) {
        this.szoveg = szoveg;
        this.szam = szam;
    }

    public String getSzoveg() {
        return szoveg;
    }

    public int getSzam() {
        return szam;
    }
    
    
}
